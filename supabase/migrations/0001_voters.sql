-- Voter Analytics schema (separate Supabase project).
-- Columns aligned to PDI / Achilles export attributes.
-- No auth.users mirror — created_by stores campaign user UUIDs as text.

create extension if not exists pg_trgm;

create table public.voters (
  id bigint generated by default as identity primary key,

  -- Civic / identity
  murmuration_id text unique,
  voter_id text unique,
  first_name text,
  last_name text,
  email text,
  phone text,
  age smallint,
  birth_year smallint,

  -- Residence
  address_line_1 text,
  city text,
  county text,
  zip text,
  state char(2),
  lat double precision,
  lng double precision,

  -- Registration
  party text,
  voter_registered text,
  status text,

  -- Achilles for Idaho > Signatures
  sig_open_primaries text,
  sig_reproductive_freedom text,
  sig_achilles_petition text,
  sig_medical_cannabis text,
  sig_medical_marijuana_valid_code text,
  sig_reproductive_freedom_valid_code text,

  -- Achilles for Idaho > Field
  volunteer_interest text,
  yard_sign text,
  support_score smallint,
  newsletter text,

  -- Achilles for Idaho > Volunteers
  legacy_volunteer text,

  -- Achilles for Idaho > Convos
  alignment_score text,
  top_main_topic text,
  alignment_label text,
  contact_tags text,
  convos_candidate_support text,
  convos_contact_status text,
  convos_poll_question text,

  -- Achilles-specific metrics
  donated text,
  attended_event text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index voters_county_idx on public.voters (county);
create index voters_party_idx on public.voters (party);
create index voters_zip_idx on public.voters (zip);
create index voters_status_idx on public.voters (status);
create index voters_age_idx on public.voters (age);
create index voters_support_score_idx on public.voters (support_score);
create index voters_lat_lng_idx on public.voters (lat, lng)
  where lat is not null and lng is not null;
create index voters_last_name_trgm_idx on public.voters using gin (lower(last_name) gin_trgm_ops);
create index voters_first_name_trgm_idx on public.voters using gin (lower(first_name) gin_trgm_ops);
create index voters_address_trgm_idx on public.voters using gin (lower(address_line_1) gin_trgm_ops);
create index voters_email_trgm_idx on public.voters using gin (lower(email) gin_trgm_ops);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger voters_set_updated_at
  before update on public.voters
  for each row execute function public.set_updated_at();

create table public.voter_import_batches (
  id uuid primary key default gen_random_uuid(),
  filename text,
  status text not null default 'running',
  total_rows integer not null default 0,
  inserted_rows integer not null default 0,
  updated_rows integer not null default 0,
  skipped_rows integer not null default 0,
  error_summary text,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger voter_import_batches_set_updated_at
  before update on public.voter_import_batches
  for each row execute function public.set_updated_at();

create table public.saved_voter_universes (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  filters jsonb not null default '{}'::jsonb,
  created_by text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index saved_voter_universes_created_by_idx
  on public.saved_voter_universes (created_by);

create trigger saved_voter_universes_set_updated_at
  before update on public.saved_voter_universes
  for each row execute function public.set_updated_at();

alter table public.voters enable row level security;
alter table public.voter_import_batches enable row level security;
alter table public.saved_voter_universes enable row level security;

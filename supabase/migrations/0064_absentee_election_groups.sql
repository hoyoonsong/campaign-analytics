-- Group absentee elections the same way as petitions (e.g. 2022 / 2024 / 2026).

create table if not exists public.absentee_election_groups (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  label text not null,
  short_label text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.absentee_election_groups enable row level security;
grant select, insert, update, delete on public.absentee_election_groups to service_role;
grant usage, select on sequence public.absentee_election_groups_id_seq to service_role;

alter table public.absentee_elections
  add column if not exists group_id bigint references public.absentee_election_groups(id)
  on delete set null;

create index if not exists absentee_elections_group_id_idx
  on public.absentee_elections (group_id)
  where group_id is not null;

do $$
begin
  if not exists (select 1 from public.absentee_election_groups) then
    insert into public.absentee_election_groups (slug, label, short_label, sort_order)
    values
      ('year_2022', '2022', '2022', 10),
      ('year_2024', '2024', '2024', 20),
      ('year_2026', '2026', '2026', 30);
  end if;
end $$;

update public.absentee_elections e
set group_id = g.id
from public.absentee_election_groups g
where e.group_id is null
  and g.slug = 'year_' || substring(e.slug from '[0-9]{4}');

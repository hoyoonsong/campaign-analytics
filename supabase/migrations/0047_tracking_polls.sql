-- Tracking poll facts. Derived metrics (first-time, movement) stay in the app.

create table if not exists public.tracking_polls (
  id bigint generated by default as identity primary key,
  poll_date date not null unique,
  label text,
  created_at timestamptz not null default now(),
  created_by text
);

create table if not exists public.tracking_poll_imports (
  id uuid primary key default gen_random_uuid(),
  poll_id bigint not null references public.tracking_polls(id) on delete cascade,
  filename text,
  file_hash text,
  imported_at timestamptz not null default now(),
  imported_by text,
  row_count integer not null default 0,
  ready_count integer not null default 0,
  matched_count integer not null default 0,
  unmatched_count integer not null default 0,
  duplicate_count integer not null default 0,
  conflict_count integer not null default 0,
  invalid_count integer not null default 0,
  imported_count integer not null default 0
);

create table if not exists public.tracking_poll_responses (
  id bigint generated by default as identity primary key,
  poll_id bigint not null references public.tracking_polls(id) on delete cascade,
  import_id uuid references public.tracking_poll_imports(id) on delete set null,
  voter_id bigint references public.voters(id) on delete set null,
  person_key text not null,
  match_method text not null default 'unmatched'
    check (match_method in ('profile_id', 'phone', 'email', 'manual', 'unmatched')),
  match_status text not null default 'unmatched'
    check (match_status in ('matched', 'unmatched', 'conflict')),
  source_profile_id text,
  source_phone text,
  source_email text,
  source_name text,
  raw_answer text,
  normalized_answer text not null
    check (normalized_answer in ('TODD', 'RISCH', 'UNDECIDED', 'OTHER', 'UNKNOWN')),
  answered_at timestamptz,
  created_at timestamptz not null default now()
);

create unique index if not exists tracking_poll_responses_poll_voter_uidx
  on public.tracking_poll_responses (poll_id, voter_id)
  where voter_id is not null;

create unique index if not exists tracking_poll_responses_poll_person_uidx
  on public.tracking_poll_responses (poll_id, person_key);

create index if not exists tracking_poll_responses_poll_idx
  on public.tracking_poll_responses (poll_id);

create index if not exists tracking_poll_responses_import_idx
  on public.tracking_poll_responses (import_id);

create index if not exists tracking_poll_responses_person_idx
  on public.tracking_poll_responses (person_key);

create index if not exists tracking_poll_imports_hash_idx
  on public.tracking_poll_imports (file_hash)
  where file_hash is not null;

alter table public.tracking_polls enable row level security;
alter table public.tracking_poll_imports enable row level security;
alter table public.tracking_poll_responses enable row level security;

grant select, insert, update, delete on public.tracking_polls to service_role;
grant select, insert, update, delete on public.tracking_poll_imports to service_role;
grant select, insert, update, delete on public.tracking_poll_responses to service_role;
grant usage, select on sequence public.tracking_polls_id_seq to service_role;
grant usage, select on sequence public.tracking_poll_responses_id_seq to service_role;

create or replace function public.lookup_voters_for_poll(
  p_profile_ids text[] default '{}'::text[],
  p_phones text[] default '{}'::text[],
  p_emails text[] default '{}'::text[]
)
returns table (
  id bigint,
  murmuration_id text,
  first_name text,
  last_name text,
  email text,
  phone text,
  phone10 text
)
language sql
stable
security definer
set search_path = public
as $$
  select
    v.id,
    v.murmuration_id,
    v.first_name,
    v.last_name,
    v.email,
    v.phone,
    right(public._phone_digits(v.phone), 10) as phone10
  from public.voters v
  where
    (
      cardinality(p_profile_ids) > 0
      and v.murmuration_id is not null
      and v.murmuration_id = any (p_profile_ids)
    )
    or (
      cardinality(p_emails) > 0
      and v.email is not null
      and lower(trim(v.email)) = any (p_emails)
    )
    or (
      cardinality(p_phones) > 0
      and v.phone is not null
      and right(public._phone_digits(v.phone), 10) = any (p_phones)
    );
$$;

revoke all on function public.lookup_voters_for_poll(text[], text[], text[]) from public;
grant execute on function public.lookup_voters_for_poll(text[], text[], text[]) to service_role;

-- Absentee ballot registry + per-voter status rows + absentee_mask.
-- Separate from signed_mask so petition math stays untouched.

set local lock_timeout = '15s';
set local deadlock_timeout = '1s';
set local statement_timeout = '300s';

create table if not exists public.absentee_elections (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  label text not null,
  short_label text not null,
  bit_index smallint not null unique check (bit_index >= 0 and bit_index <= 62),
  sort_order integer not null default 0,
  is_default boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by text
);

alter table public.absentee_elections enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_attribute
    where attrelid = 'public.voters'::regclass
      and attname = 'absentee_mask'
      and not attisdropped
  ) then
    alter table public.voters
      add column absentee_mask bigint not null default 0;
  end if;
end $$;

create table if not exists public.voter_absentee_ballots (
  voter_id bigint not null references public.voters(id) on delete cascade,
  election_id bigint not null references public.absentee_elections(id) on delete cascade,
  status text not null default 'UNKNOWN'
    check (status in (
      'REQUESTED', 'ISSUED', 'MAILED', 'RETURNED',
      'ACCEPTED', 'REJECTED', 'CANCELLED', 'UNKNOWN'
    )),
  raw_status text,
  requested_at date,
  issued_at date,
  returned_at date,
  import_batch_id uuid,
  updated_at timestamptz not null default now(),
  primary key (voter_id, election_id)
);

create index if not exists voter_absentee_ballots_election_idx
  on public.voter_absentee_ballots (election_id);

create index if not exists voter_absentee_ballots_status_idx
  on public.voter_absentee_ballots (status);

create index if not exists voter_absentee_ballots_batch_idx
  on public.voter_absentee_ballots (import_batch_id)
  where import_batch_id is not null;

alter table public.voter_absentee_ballots enable row level security;

create or replace function public._absentee_counts_for_mask(p_status text)
returns boolean
language sql
immutable
parallel safe
as $$
  select p_status in (
    'REQUESTED', 'ISSUED', 'MAILED', 'RETURNED', 'ACCEPTED', 'REJECTED'
  );
$$;

create or replace function public._absentee_mask(slugs text[])
returns bigint
language sql
stable
as $$
  select coalesce((
    select bit_or(1::bigint << e.bit_index)
    from public.absentee_elections e
    where e.is_active
      and slugs is not null
      and e.slug = any (slugs)
  ), 0::bigint);
$$;

create or replace function public._sync_voter_absentee_mask()
returns trigger
language plpgsql
as $$
declare
  v_id bigint;
  v_bit smallint;
  v_on boolean;
begin
  if tg_op = 'DELETE' then
    v_id := old.voter_id;
    select bit_index into v_bit from public.absentee_elections where id = old.election_id;
    if v_bit is not null then
      update public.voters
      set absentee_mask = absentee_mask & ~ (1::bigint << v_bit)
      where id = v_id;
    end if;
    return old;
  end if;

  v_id := new.voter_id;
  v_on := public._absentee_counts_for_mask(new.status);
  select bit_index into v_bit from public.absentee_elections where id = new.election_id;
  if v_bit is null then
    return new;
  end if;
  if v_on then
    update public.voters
    set absentee_mask = absentee_mask | (1::bigint << v_bit)
    where id = v_id;
  else
    update public.voters
    set absentee_mask = absentee_mask & ~ (1::bigint << v_bit)
    where id = v_id;
  end if;
  return new;
end;
$$;

drop trigger if exists voter_absentee_ballots_mask on public.voter_absentee_ballots;
create trigger voter_absentee_ballots_mask
  after insert or update of status, election_id or delete
  on public.voter_absentee_ballots
  for each row execute function public._sync_voter_absentee_mask();

do $$
begin
  if not exists (
    select 1
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relname = 'voters_absentee_mask_idx'
  ) then
    execute $idx$
      create index voters_absentee_mask_idx
        on public.voters (absentee_mask)
        where absentee_mask <> 0
    $idx$;
  end if;
end $$;

create or replace function public.next_absentee_bit_index()
returns smallint
language sql
stable
as $$
  select g.n::smallint
  from generate_series(0, 62) as g(n)
  where not exists (
    select 1 from public.absentee_elections e where e.bit_index = g.n
  )
  order by g.n
  limit 1;
$$;

create or replace function public.create_absentee_election(
  p_label text,
  p_slug text default null,
  p_short_label text default null,
  p_is_default boolean default false,
  p_actor text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slug text;
  v_short text;
  v_bit smallint;
  rec public.absentee_elections;
begin
  v_slug := nullif(trim(coalesce(p_slug, '')), '');
  if v_slug is null then
    v_slug := trim(both '_' from lower(regexp_replace(coalesce(p_label, ''), '[^a-zA-Z0-9]+', '_', 'g')));
  end if;
  v_slug := left(v_slug, 64);
  if v_slug is null or v_slug = '' then
    return jsonb_build_object('error', 'label is required');
  end if;

  select * into rec from public.absentee_elections where slug = v_slug;
  if found then
    return to_jsonb(rec);
  end if;

  v_bit := public.next_absentee_bit_index();
  if v_bit is null then
    return jsonb_build_object('error', 'No free absentee bit_index (max 63)');
  end if;

  v_short := nullif(trim(coalesce(p_short_label, '')), '');
  if v_short is null then
    v_short := left(coalesce(p_label, v_slug), 16);
  end if;

  insert into public.absentee_elections (
    slug, label, short_label, bit_index, sort_order, is_default, is_active, created_by
  )
  values (
    v_slug,
    coalesce(nullif(trim(p_label), ''), v_slug),
    v_short,
    v_bit,
    coalesce((select max(sort_order) + 10 from public.absentee_elections), 10),
    coalesce(p_is_default, false),
    true,
    p_actor
  )
  returning * into rec;

  return to_jsonb(rec);
end;
$$;

create or replace function public.delete_absentee_election(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  rec public.absentee_elections;
  v_bit smallint;
begin
  select * into rec from public.absentee_elections where id = p_id;
  if not found then
    return jsonb_build_object('error', 'Election not found');
  end if;
  v_bit := rec.bit_index;
  delete from public.voter_absentee_ballots where election_id = p_id;
  delete from public.absentee_elections where id = p_id;
  if v_bit is not null then
    update public.voters
    set absentee_mask = absentee_mask & ~ (1::bigint << v_bit)
    where (absentee_mask & (1::bigint << v_bit)) <> 0;
  end if;
  return to_jsonb(rec);
end;
$$;

create or replace function public._import_absentee_status(val text)
returns text
language sql
immutable
parallel safe
as $$
  select case
    when val is null or trim(val) = '' then 'UNKNOWN'
    when lower(trim(val)) in (
      'false', 'f', 'no', 'n', '0', 'none', 'null', '-', 'unsigned'
    ) then 'UNKNOWN'
    when lower(trim(val)) ~ '(reject|spoil|challenge|invalid)' then 'REJECTED'
    when lower(trim(val)) ~ '(cancel|void|withdraw|undeliver)' then 'CANCELLED'
    when lower(trim(val)) ~ '(accept|count|canvass|valid)' then 'ACCEPTED'
    when lower(trim(val)) ~ '(return|receiv|in.?clerk|in.?office)' then 'RETURNED'
    when lower(trim(val)) ~ '(mail|sent|send)' then 'MAILED'
    when lower(trim(val)) ~ '(issu)' then 'ISSUED'
    when lower(trim(val)) ~ '(request|appl|absentee|early|yes|true|y|1)' then 'REQUESTED'
    else 'REQUESTED'
  end;
$$;

create or replace function public._parse_import_date(val text)
returns date
language plpgsql
immutable
as $$
declare
  t text := nullif(trim(coalesce(val, '')), '');
  d date;
begin
  if t is null then
    return null;
  end if;
  begin
    d := t::date;
    return d;
  exception when others then
    null;
  end;
  begin
    d := to_date(t, 'MM/DD/YYYY');
    return d;
  exception when others then
    null;
  end;
  begin
    d := to_date(t, 'M/D/YYYY');
    return d;
  exception when others then
    return null;
  end;
end;
$$;

create or replace function public.voter_apply_batch_absentee(
  rows jsonb,
  batch_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  n_applied int := 0;
begin
  if rows is null or jsonb_typeof(rows) <> 'array' then
    return jsonb_build_object('applied', 0);
  end if;

  drop table if exists _abs_incoming;
  create temporary table _abs_incoming on commit drop as
  with incoming as (
    select
      nullif(trim(r->>'murmuration_id'), '') as murmuration_id,
      nullif(trim(r->>'voter_id'), '') as voter_id,
      kv.key as slug,
      nullif(trim(kv.value #>> '{}'), '') as raw_status,
      public._parse_import_date(r->>'absentee_requested_at') as requested_at,
      public._parse_import_date(r->>'absentee_issued_at') as issued_at,
      public._parse_import_date(r->>'absentee_returned_at') as returned_at
    from jsonb_array_elements(rows) r
    cross join lateral jsonb_each(coalesce(r->'absentee', '{}'::jsonb)) kv
    where jsonb_typeof(coalesce(r->'absentee', 'null'::jsonb)) = 'object'
  )
  select
    v.id as voter_id,
    e.id as election_id,
    e.slug,
    i.raw_status,
    public._import_absentee_status(i.raw_status) as status,
    i.requested_at,
    i.issued_at,
    i.returned_at
  from incoming i
  join public.absentee_elections e on e.slug = i.slug and e.is_active
  join public.voters v
    on (
      i.murmuration_id is not null
      and v.murmuration_id = i.murmuration_id
    )
    or (
      i.murmuration_id is null
      and i.voter_id is not null
      and v.voter_id = i.voter_id
    )
  where i.raw_status is not null
    and public._import_absentee_status(i.raw_status) <> 'UNKNOWN';

  insert into public.voter_absentee_ballots (
    voter_id, election_id, status, raw_status,
    requested_at, issued_at, returned_at, import_batch_id, updated_at
  )
  select
    voter_id, election_id, status, raw_status,
    requested_at, issued_at, returned_at, batch_id, now()
  from _abs_incoming
  on conflict (voter_id, election_id) do update set
    status = excluded.status,
    raw_status = excluded.raw_status,
    requested_at = coalesce(excluded.requested_at, public.voter_absentee_ballots.requested_at),
    issued_at = coalesce(excluded.issued_at, public.voter_absentee_ballots.issued_at),
    returned_at = coalesce(excluded.returned_at, public.voter_absentee_ballots.returned_at),
    import_batch_id = coalesce(excluded.import_batch_id, public.voter_absentee_ballots.import_batch_id),
    updated_at = now();

  get diagnostics n_applied = row_count;
  return jsonb_build_object('applied', n_applied);
end;
$$;

create or replace function public.absentee_dashboard()
returns json
language sql
stable
security definer
set search_path = public
as $$
  select json_build_object(
    'elections', coalesce((
      select json_agg(e)
      from (
        select id, slug, label, short_label, bit_index, sort_order,
               is_default, is_active, created_at
        from public.absentee_elections
        order by sort_order, slug
      ) e
    ), '[]'::json),
    'ballots', coalesce((
      select json_agg(b)
      from (
        select
          a.voter_id,
          a.election_id,
          e.slug as election_slug,
          a.status,
          a.requested_at,
          a.issued_at,
          a.returned_at,
          v.party,
          v.county,
          v.age,
          v.signed_mask
        from public.voter_absentee_ballots a
        join public.absentee_elections e on e.id = a.election_id
        join public.voters v on v.id = a.voter_id
        order by a.election_id, a.voter_id
      ) b
    ), '[]'::json)
  );
$$;

create or replace function public._filters_have_absentee(f jsonb)
returns boolean
language sql
immutable
as $$
  select
    coalesce(jsonb_typeof(f->'absentee'), 'null') = 'array'
      and jsonb_array_length(f->'absentee') > 0
    or coalesce(jsonb_typeof(f->'absentee_status'), 'null') = 'array'
      and jsonb_array_length(f->'absentee_status') > 0
    or coalesce(jsonb_typeof(f->'exclude_absentee'), 'null') = 'array'
      and jsonb_array_length(f->'exclude_absentee') > 0
    or coalesce(jsonb_typeof(f->'exclude_absentee_status'), 'null') = 'array'
      and jsonb_array_length(f->'exclude_absentee_status') > 0;
$$;

create or replace function public._voter_matches_absentee(v public.voters, filters jsonb)
returns boolean
language plpgsql
stable
as $$
declare
  f jsonb := coalesce(filters, '{}'::jsonb);
  want_slugs text[];
  excl_slugs text[];
  want_status text[];
  excl_status text[];
  need_mask bigint;
  excl_mask bigint;
  status_ok boolean;
  excl_status_hit boolean;
begin
  if not public._filters_have_absentee(f) then
    return true;
  end if;

  want_slugs := public._jsonb_text_array(f, 'absentee');
  excl_slugs := public._jsonb_text_array(f, 'exclude_absentee');
  want_status := public._jsonb_text_array(f, 'absentee_status');
  excl_status := public._jsonb_text_array(f, 'exclude_absentee_status');
  need_mask := public._absentee_mask(want_slugs);
  excl_mask := public._absentee_mask(excl_slugs);

  if need_mask <> 0 and (coalesce(v.absentee_mask, 0) & need_mask) <> need_mask then
    return false;
  end if;
  if excl_mask <> 0 and (coalesce(v.absentee_mask, 0) & excl_mask) <> 0 then
    return false;
  end if;

  if want_status is not null then
    select exists (
      select 1
      from public.voter_absentee_ballots b
      join public.absentee_elections e on e.id = b.election_id
      where b.voter_id = v.id
        and b.status = any (want_status)
        and (
          want_slugs is null
          or e.slug = any (want_slugs)
        )
    ) into status_ok;
    if not status_ok then
      return false;
    end if;
  end if;

  if excl_status is not null then
    select exists (
      select 1
      from public.voter_absentee_ballots b
      join public.absentee_elections e on e.id = b.election_id
      where b.voter_id = v.id
        and b.status = any (excl_status)
        and (
          excl_slugs is null
          or e.slug = any (excl_slugs)
        )
    ) into excl_status_hit;
    if excl_status_hit then
      return false;
    end if;
  end if;

  return true;
end;
$$;

do $$
begin
  if exists (
    select 1
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = 'voters_match_filters'
      and not exists (

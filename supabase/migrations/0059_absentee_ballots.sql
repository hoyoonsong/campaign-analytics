  end if;
end $$;

create or replace function public.voters_match_filters(v public.voters, filters jsonb)
returns boolean
language sql
stable
as $$
  select public.voters_match_filters_base(v, filters)
    and public._voter_matches_absentee(v, filters);
$$;

create or replace function public.voter_search_absentee(
  filters jsonb default '{}'::jsonb,
  q text default '',
  page integer default 1,
  page_size integer default 50
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
set statement_timeout = '300s'
set jit = off
as $$
declare
  safe_page int := greatest(coalesce(page, 1), 1);
  safe_size int := least(greatest(coalesce(page_size, 50), 1), 100);
  offset_rows int;
  total_count bigint;
  rows_json jsonb;
  needle text := nullif(trim(coalesce(q, '')), '');
begin
  offset_rows := (safe_page - 1) * safe_size;

  with filtered as (
    select v.id, v.murmuration_id, v.voter_id, v.first_name, v.last_name,
           v.email, v.phone, v.address_line_1, v.city, v.state, v.zip,
           v.county, v.party, v.age, v.status, v.support_score, v.lat, v.lng,
           v.supporter_tag, v.is_campaign_volunteer, v.campaign_person_id
    from public.voters v
    where public.voters_match_filters(v, coalesce(filters, '{}'::jsonb))
      and (
        needle is null
        or v.voter_id ilike '%' || needle || '%'
        or v.murmuration_id ilike '%' || needle || '%'
        or v.first_name ilike '%' || needle || '%'
        or v.last_name ilike '%' || needle || '%'
        or (coalesce(v.first_name, '') || ' ' || coalesce(v.last_name, '')) ilike '%' || needle || '%'
        or v.address_line_1 ilike '%' || needle || '%'
        or v.city ilike '%' || needle || '%'
        or v.zip ilike '%' || needle || '%'
        or v.email ilike '%' || needle || '%'
        or v.phone ilike '%' || needle || '%'
      )
  )
  select count(*) into total_count from filtered;

  select coalesce(
    jsonb_agg(to_jsonb(t) order by t.last_name nulls last, t.first_name nulls last, t.id),
    '[]'::jsonb
  )
  into rows_json
  from (
    select *
    from filtered
    order by last_name nulls last, first_name nulls last, id
    offset offset_rows
    limit safe_size
  ) t;

  return jsonb_build_object(
    'rows', coalesce(rows_json, '[]'::jsonb),
    'total', coalesce(total_count, 0),
    'page', safe_page,
    'page_size', safe_size
  );
end;
$$;

create or replace function public.voter_search(
  filters jsonb default '{}'::jsonb,
  q text default ''::text,
  page integer default 1,
  page_size integer default 50
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
set statement_timeout = '300s'
set jit = off
as $$
declare
  f jsonb := coalesce(filters, '{}'::jsonb);
  extras jsonb := f - 'possible_duplicates';
  needle text := nullif(trim(coalesce(q, '')), '');
  safe_page int := greatest(coalesce(page, 1), 1);
  safe_size int := least(greatest(coalesce(page_size, 50), 1), 100);
  offset_rows int;
  extras_empty boolean;
  total_count bigint;
  rows_json jsonb;
begin
  if public._filters_have_absentee(f) then
    return public.voter_search_absentee(filters, q, page, page_size);
  end if;

  select coalesce(bool_and(
    value is null
    or value = 'null'::jsonb
    or value = '[]'::jsonb
    or value = '""'::jsonb
    or value = 'false'::jsonb
  ), true)
  into extras_empty
  from jsonb_each(coalesce(extras, '{}'::jsonb));

  if extras = '{}'::jsonb or extras is null then
    extras_empty := true;
  end if;

  if coalesce(nullif(f->>'possible_duplicates', '')::boolean, false)
     and needle is null
     and extras_empty
  then
    perform public.ensure_possible_duplicates();
    offset_rows := (safe_page - 1) * safe_size;
    select count(*) into total_count from public.possible_duplicate_voters;
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', t.id,
          'murmuration_id', t.murmuration_id,
          'voter_id', t.voter_id,
          'first_name', t.first_name,
          'last_name', t.last_name,
          'email', t.email,
          'phone', t.phone,
          'address_line_1', t.address_line_1,
          'city', t.city,
          'state', t.state,
          'zip', t.zip,
          'county', t.county,
          'party', t.party,
          'age', t.age,
          'status', t.status,
          'support_score', t.support_score,
          'lat', t.lat,
          'lng', t.lng,
          'supporter_tag', t.supporter_tag,
          'is_campaign_volunteer', t.is_campaign_volunteer,
          'campaign_person_id', t.campaign_person_id,
          'nearby_yard_sign_miles', null,
          'nearby_volunteer_miles', null
        )
        order by t.last_name nulls last, t.first_name nulls last, t.id
      ),
      '[]'::jsonb
    )
    into rows_json
    from (
      select
        v.id, v.murmuration_id, v.voter_id, v.first_name, v.last_name, v.email, v.phone,
        v.address_line_1, v.city, v.state, v.zip, v.county, v.party, v.age, v.status,
        v.support_score, v.lat, v.lng, v.supporter_tag, v.is_campaign_volunteer,
        v.campaign_person_id
      from public.possible_duplicate_voters d
      join public.voters v on v.id = d.id
      order by v.last_name nulls last, v.first_name nulls last, v.id
      offset offset_rows
      limit safe_size
    ) t;
    return jsonb_build_object(
      'rows', coalesce(rows_json, '[]'::jsonb),
      'total', coalesce(total_count, 0),
      'page', safe_page,
      'page_size', safe_size
    );
  end if;

  if coalesce(nullif(f->>'possible_duplicates', '')::boolean, false) then
    perform public.ensure_possible_duplicates();
  end if;

  return public.voter_search_core(filters, q, page, page_size);
end;
$$;

do $$
begin
  if exists (
    select 1
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = 'voter_export_page'
      and not exists (
        select 1
        from pg_proc p2
        join pg_namespace n2 on n2.oid = p2.pronamespace
        where n2.nspname = 'public'
          and p2.proname = 'voter_export_page_core'
      )
  ) then
    alter function public.voter_export_page(jsonb, bigint, int)
      rename to voter_export_page_core;
  end if;
end $$;

create or replace function public.voter_export_page_absentee(
  filters jsonb default '{}'::jsonb,
  after_id bigint default null,
  lim int default 1000
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  safe_limit int := least(greatest(coalesce(lim, 1000), 1), 5000);
  rows_json jsonb;
  next_cursor bigint;
begin
  with filtered as (
    select
      v.id, v.voter_id, v.first_name, v.last_name, v.email, v.phone, v.age,
      v.address_line_1, v.city, v.county, v.zip, v.state, v.lat, v.lng,
      v.party, v.voter_registered, v.status,
      v.volunteer_interest, v.yard_sign, v.support_score, v.newsletter,
      v.alignment_score, v.top_main_topic, v.alignment_label,
      v.contact_tags, v.convos_candidate_support, v.convos_contact_status,
      v.donated, v.attended_event, v.supporter_tag
    from public.voters v
    where public.voters_match_filters(v, coalesce(filters, '{}'::jsonb))
      and (after_id is null or v.id > after_id)
    order by v.id
    limit safe_limit
  )
  select
    coalesce(jsonb_agg(to_jsonb(filtered) order by id), '[]'::jsonb),
    max(id)
  into rows_json, next_cursor
  from filtered;

  return jsonb_build_object(
    'rows', rows_json,
    'next_cursor', case
      when jsonb_array_length(rows_json) < safe_limit then null
      else next_cursor
    end
  );
end;
$$;


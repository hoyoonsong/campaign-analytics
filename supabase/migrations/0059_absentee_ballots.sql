create or replace function public._merge_absentee_for_pair(keep_id bigint, drop_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  begin
    insert into public.voter_absentee_ballots (
      voter_id, election_id, status, raw_status,
      requested_at, issued_at, returned_at, import_batch_id, updated_at
    )
    select
      keep_id, s.election_id, s.status, s.raw_status,
      s.requested_at, s.issued_at, s.returned_at, s.import_batch_id, s.updated_at
    from public.voter_absentee_ballots s
    where s.voter_id = drop_id
    on conflict (voter_id, election_id) do update
      set status = excluded.status,
          raw_status = coalesce(public.voter_absentee_ballots.raw_status, excluded.raw_status),
          requested_at = coalesce(public.voter_absentee_ballots.requested_at, excluded.requested_at),
          issued_at = coalesce(public.voter_absentee_ballots.issued_at, excluded.issued_at),
          returned_at = coalesce(public.voter_absentee_ballots.returned_at, excluded.returned_at),
          updated_at = now();
    delete from public.voter_absentee_ballots where voter_id = drop_id;
  exception when undefined_table then
    null;
  end;
end;
$$;

do $$
begin
  if exists (
    select 1
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.proname = '_merge_voter_pair'
      and not exists (
        select 1
        from pg_proc p2
        join pg_namespace n2 on n2.oid = p2.pronamespace
        where n2.nspname = 'public'
          and p2.proname = '_merge_voter_pair_base'
      )
  ) then
    alter function public._merge_voter_pair(bigint, bigint)
      rename to _merge_voter_pair_base;
  end if;
end $$;

create or replace function public._merge_voter_pair(keep_id bigint, drop_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform public._merge_absentee_for_pair(keep_id, drop_id);
  perform public._merge_voter_pair_base(keep_id, drop_id);
  begin
    update public.voters v
    set absentee_mask = coalesce(v.absentee_mask, 0)
    where v.id = keep_id;
  exception when undefined_column then
    null;
  end;
end;
$$;


-- Statewide election-day and early-voting sites, plus each voter's nearest site.

set local lock_timeout = '15s';
set local deadlock_timeout = '1s';
set local statement_timeout = '120s';

create or replace function public._county_key(p text)
returns text
language sql
immutable
parallel safe
as $$
  select nullif(
    lower(trim(regexp_replace(coalesce(p, ''), '[[:space:]]*county[[:space:]]*', '', 'gi'))),
    ''
  );
$$;

create table if not exists public.polling_locations (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('election_day', 'early_voting')),
  external_key text not null,
  name text not null,
  address_line_1 text,
  address_line_2 text,
  city text,
  zip text,
  county text,
  state char(2) not null default 'ID',
  status text,
  availability text,
  precinct_combos text,
  precinct_names text,
  poll_ids text,
  active_voters integer,
  lat double precision,
  lng double precision,
  assigned_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (kind, external_key)
);

create index if not exists polling_locations_kind_county_idx
  on public.polling_locations (kind, county);

create index if not exists polling_locations_lat_lng_idx
  on public.polling_locations (lat, lng)
  where lat is not null and lng is not null;

drop trigger if exists polling_locations_set_updated_at on public.polling_locations;
create trigger polling_locations_set_updated_at
  before update on public.polling_locations
  for each row execute function public.set_updated_at();

create table if not exists public.voter_nearest_polls (
  voter_id bigint primary key references public.voters(id) on delete cascade,
  election_day_id bigint references public.polling_locations(id) on delete set null,
  election_day_miles double precision,
  early_voting_id bigint references public.polling_locations(id) on delete set null,
  early_voting_miles double precision,
  updated_at timestamptz not null default now()
);

create index if not exists voter_nearest_polls_election_idx
  on public.voter_nearest_polls (election_day_id)
  where election_day_id is not null;

create index if not exists voter_nearest_polls_early_idx
  on public.voter_nearest_polls (early_voting_id)
  where early_voting_id is not null;

create index if not exists voters_county_key_lat_idx
  on public.voters (public._county_key(county))
  where lat is not null and lng is not null;

alter table public.polling_locations enable row level security;
alter table public.voter_nearest_polls enable row level security;

create or replace function public.refresh_polling_assigned_counts()
returns void
language plpgsql
volatile
as $$
begin
  update public.polling_locations
  set assigned_count = 0
  where id is not null;

  update public.polling_locations p
  set assigned_count = sub.n
  from (
    select election_day_id as id, count(*)::int as n
    from public.voter_nearest_polls
    where election_day_id is not null
    group by 1
  ) sub
  where p.id = sub.id;

  update public.polling_locations p
  set assigned_count = sub.n
  from (
    select early_voting_id as id, count(*)::int as n
    from public.voter_nearest_polls
    where early_voting_id is not null
    group by 1
  ) sub
  where p.id = sub.id;
end;
$$;

create or replace function public.polling_assignment_links(p_county text, p_kind text)
returns jsonb
language plpgsql
volatile
as $$
declare
  n int;
  payload jsonb;
begin
  perform set_config('statement_timeout', '30s', true);

  if p_kind not in ('election_day', 'early_voting') then
    return jsonb_build_object('total', 0, 'truncated', false, 'links', '[]'::jsonb);
  end if;

  select count(*) into n
  from public.voter_nearest_polls a
  join public.voters v on v.id = a.voter_id
  where public._county_key(v.county) = public._county_key(p_county)
    and v.lat is not null
    and v.lng is not null
    and (
      (p_kind = 'election_day' and a.election_day_id is not null)
      or (p_kind = 'early_voting' and a.early_voting_id is not null)
    );

  if n > 12000 then
    return jsonb_build_object('total', n, 'truncated', true, 'links', '[]'::jsonb);
  end if;

  select coalesce(jsonb_agg(jsonb_build_array(
    round(v.lat::numeric, 5),
    round(v.lng::numeric, 5),
    round(p.lat::numeric, 5),
    round(p.lng::numeric, 5)
  )), '[]'::jsonb)
  into payload
  from public.voter_nearest_polls a
  join public.voters v on v.id = a.voter_id
  join public.polling_locations p
    on p.id = case
      when p_kind = 'early_voting' then a.early_voting_id
      else a.election_day_id
    end
  where public._county_key(v.county) = public._county_key(p_county)
    and v.lat is not null
    and p.lat is not null
    and p.lng is not null;

  return jsonb_build_object('total', n, 'truncated', false, 'links', payload);
end;
$$;

grant select, insert, update, delete on public.polling_locations to service_role;
grant select, insert, update, delete on public.voter_nearest_polls to service_role;
grant usage, select on sequence public.polling_locations_id_seq to service_role;

revoke all on function public._county_key(text) from public;
grant execute on function public._county_key(text) to service_role;
revoke all on function public.refresh_polling_assigned_counts() from public;
grant execute on function public.refresh_polling_assigned_counts() to service_role;
revoke all on function public.polling_assignment_links(text, text) from public;
grant execute on function public.polling_assignment_links(text, text) to service_role;

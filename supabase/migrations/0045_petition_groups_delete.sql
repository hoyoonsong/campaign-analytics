-- Petition groups (similar petitions share a bar / export) + safe delete.

create table if not exists public.petition_groups (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  label text not null,
  short_label text not null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.petition_groups enable row level security;

grant select, insert, update, delete on public.petition_groups to service_role;
grant usage, select on sequence public.petition_groups_id_seq to service_role;

alter table public.petitions
  add column if not exists group_id bigint references public.petition_groups(id)
    on delete set null;

create index if not exists petitions_group_id_idx
  on public.petitions (group_id)
  where group_id is not null;

-- Skip the per-row signed_mask trigger (would UPDATE voters once per signature).
create or replace function public.delete_petition(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  rec public.petitions;
  v_bit smallint;
begin
  select * into rec from public.petitions where id = p_id;
  if not found then
    return jsonb_build_object('error', 'Petition not found');
  end if;
  v_bit := rec.bit_index;

  perform set_config('session_replication_role', 'replica', true);
  begin
    delete from public.voter_petition_signatures where petition_id = p_id;
    delete from public.petitions where id = p_id;
    perform set_config('session_replication_role', 'origin', true);
  exception
    when others then
      perform set_config('session_replication_role', 'origin', true);
      raise;
  end;

  if v_bit is not null then
    update public.voters
    set signed_mask = signed_mask & ~ (1::bigint << v_bit)
    where (coalesce(signed_mask, 0) & (1::bigint << v_bit)) <> 0;
  end if;

  update public.campaign_sync_state
  set analytics_summary_cache = null,
      analytics_summary_cached_at = null
  where id = 1;

  return to_jsonb(rec);
end;
$$;

revoke all on function public.delete_petition(bigint) from public;
grant execute on function public.delete_petition(bigint) to service_role;

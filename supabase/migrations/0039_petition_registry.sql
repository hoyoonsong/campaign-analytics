-- Petition registry + per-voter signature join table + signed_mask.
-- Existing sig_* columns stay for dual-write / export; filters use signed_mask.
--
-- Lock order is intentional to avoid deadlocks with live analytics/search:
-- 1) new tables + helpers (no exclusive lock on voters)
-- 2) ADD COLUMN (metadata-only with constant default)
-- 3) backfill signatures WITHOUT the mask trigger
-- 4) one set-based signed_mask update
-- 5) install trigger, then index

set local lock_timeout = '15s';
set local deadlock_timeout = '1s';
set local statement_timeout = '300s';

create table if not exists public.petitions (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  label text not null,
  short_label text not null,
  bit_index smallint not null unique check (bit_index >= 0 and bit_index <= 62),
  sort_order integer not null default 0,
  is_default boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  created_by text
);

alter table public.petitions enable row level security;

create or replace function public._popcount(n bigint)
returns integer
language sql
immutable
parallel safe
as $$
  select case
    when n is null or n = 0 then 0
    else length(replace((n::bit(64))::text, '0', ''))
  end;
$$;

create or replace function public._petition_mask(slugs text[])
returns bigint
language sql
stable
as $$
  select coalesce((
    select bit_or(1::bigint << p.bit_index)
    from public.petitions p
    where p.is_active
      and slugs is not null
      and p.slug = any (slugs)
  ), 0::bigint);
$$;

create or replace function public._core_petition_mask()
returns bigint
language sql
stable
as $$
  select public._petition_mask(
    array['open_primaries', 'reproductive_freedom', 'achilles']::text[]
  );
$$;

create or replace function public._default_petition_slugs()
returns text[]
language sql
stable
as $$
  select coalesce(
    array_agg(p.slug order by p.sort_order, p.slug),
    '{}'::text[]
  )
  from public.petitions p
  where p.is_active and p.is_default;
$$;


-- One join instead of a correlated subquery per voter.
update public.voters v
set signed_mask = s.mask
from (
  select
    sig.voter_id,
    bit_or(1::bigint << p.bit_index) as mask
  from public.voter_petition_signatures sig
  join public.petitions p on p.id = sig.petition_id
  where sig.signed
  group by sig.voter_id
) s
where v.id = s.voter_id
  and v.signed_mask is distinct from s.mask;

create trigger voter_petition_signatures_mask
  after insert or update of signed, petition_id or delete
  on public.voter_petition_signatures
  for each row execute function public._sync_voter_signed_mask();

-- Skip if the index already exists so a re-run does not ShareLock voters.
do $$
begin
  if not exists (
    select 1
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relname = 'voters_signed_mask_idx'
  ) then
    execute $idx$
      create index voters_signed_mask_idx
        on public.voters (signed_mask)
        where signed_mask <> 0
    $idx$;
  end if;
end $$;


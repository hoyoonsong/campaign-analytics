-- Skip ALTER when the column already exists so a re-run does not take
-- AccessExclusiveLock on voters (that deadlocks with live analytics SELECTs).
do $$
begin
  if not exists (
    select 1
    from pg_attribute
    where attrelid = 'public.voters'::regclass
      and attname = 'signed_mask'
      and not attisdropped
  ) then
    alter table public.voters
      add column signed_mask bigint not null default 0;
  end if;
end $$;

create table if not exists public.voter_petition_signatures (
  voter_id bigint not null references public.voters(id) on delete cascade,
  petition_id bigint not null references public.petitions(id) on delete cascade,
  raw_value text,
  signed boolean not null default false,
  import_batch_id uuid,
  updated_at timestamptz not null default now(),
  primary key (voter_id, petition_id)
);

create index if not exists voter_petition_signatures_petition_idx
  on public.voter_petition_signatures (petition_id)
  where signed;

create index if not exists voter_petition_signatures_batch_idx
  on public.voter_petition_signatures (import_batch_id)
  where import_batch_id is not null;

alter table public.voter_petition_signatures enable row level security;

-- Trigger function exists, but is NOT attached until after backfill.
create or replace function public._sync_voter_signed_mask()
returns trigger
language plpgsql
as $$
declare
  v_id bigint;
  v_bit smallint;
  v_signed boolean;
begin
  if tg_op = 'DELETE' then
    v_id := old.voter_id;
    select bit_index into v_bit from public.petitions where id = old.petition_id;
    if v_bit is not null then
      update public.voters
      set signed_mask = signed_mask & ~ (1::bigint << v_bit)
      where id = v_id;
    end if;
    return old;
  end if;

  v_id := new.voter_id;
  v_signed := new.signed;
  select bit_index into v_bit from public.petitions where id = new.petition_id;
  if v_bit is null then
    return new;
  end if;
  if v_signed then
    update public.voters
    set signed_mask = signed_mask | (1::bigint << v_bit)
    where id = v_id;
  else
    update public.voters
    set signed_mask = signed_mask & ~ (1::bigint << v_bit)
    where id = v_id;
  end if;
  return new;
end;
$$;

-- Drop any leftover trigger from a failed prior run so backfill does not
-- UPDATE voters once per signature row (that deadlocks with live SELECTs).
drop trigger if exists voter_petition_signatures_mask on public.voter_petition_signatures;

insert into public.voter_petition_signatures (voter_id, petition_id, raw_value, signed)
select v.id, p.id, nullif(trim(v.sig_open_primaries), ''), true
from public.voters v
join public.petitions p on p.slug = 'open_primaries'
where public._is_signed(v.sig_open_primaries)
on conflict (voter_id, petition_id) do nothing;

insert into public.voter_petition_signatures (voter_id, petition_id, raw_value, signed)
